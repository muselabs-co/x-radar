let currentLocale = 'en';

export function normalizeLocale(input) {
  const value = String(input || '').toLowerCase().replace('_', '-');
  if (!value) return '';
  if (value.startsWith('zh')) return 'zh';
  if (value.startsWith('ja')) return 'ja';
  if (value.startsWith('ko')) return 'ko';
  if (value.startsWith('vi')) return 'vi';
  if (value.startsWith('es')) return 'es';
  if (value.startsWith('pt')) return 'pt';
  if (value.startsWith('en')) return 'en';
  return '';
}

export function detectLocale() {
  const candidates = Array.isArray(navigator.languages) && navigator.languages.length
    ? navigator.languages
    : [navigator.language];
  for (const candidate of candidates) {
    const locale = normalizeLocale(candidate);
    if (locale) return locale;
  }
  return 'en';
}

export function getLocale() {
  return currentLocale;
}

export function t(key, vars) {
  const table = MESSAGES[currentLocale] || MESSAGES.en;
  const template = table[key] || MESSAGES.en[key] || key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) => (
    vars[name] == null ? '' : String(vars[name])
  ));
}

export function translateError(message) {
  const text = String(message || '');
  if (!text) return t('error.unknown');
  if (text.includes('RATE_LIMITED') || text.includes('频率限制') || text.includes('次数限制')) {
    return t('error.rateLimit');
  }
  if (
    text.includes('AUTH_ERROR') ||
    text.includes('未登录') ||
    text.includes('登录态') ||
    text.includes('登录凭证') ||
    text.includes('ct0')
  ) {
    return t('error.auth');
  }
  if (text.includes('SYNC_CANCELLED') || text.includes('同步已取消') || text.includes('已由用户取消')) {
    return t('error.cancelled');
  }
  if (text.includes('已经在同步')) return t('error.alreadySyncing');
  if (text.includes('无法确认') || text.includes('账号 ID')) return t('error.noUserId');
  if (text.includes('SCAN_INCOMPLETE')) return t('error.incomplete');
  if (text.includes('SCAN_TOO_LARGE')) return t('error.tooLarge');
  if (text.includes('SCAN_INTERRUPTED')) return t('error.interrupted');
  if (text.includes('STORAGE_QUOTA')) return t('error.storage');
  return text;
}

export function applyStaticText(root = document) {
  const meta = LOCALES.find((item) => item.id === currentLocale) || LOCALES[1];
  document.documentElement.lang = meta.htmlLang;
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
}

export async function loadLocale() {
  try {
    const stored = await chrome.storage.local.get(STORAGE_KEY);
    if (stored[STORAGE_KEY]) {
      currentLocale = normalizeLocale(stored[STORAGE_KEY]) || 'en';
      return currentLocale;
    }
  } catch (e) {
    currentLocale = 'en';
    return currentLocale;
  }
  currentLocale = detectLocale();
  return currentLocale;
}

export async function setLocale(locale) {
  currentLocale = normalizeLocale(locale) || 'en';
  await chrome.storage.local.set({ [STORAGE_KEY]: currentLocale });
  return currentLocale;
}
